// Builds dist/tui.js, the TUI part (the /unii popup and the sidebar line) as OpenCode loads it
// from an installed package. Run `bun run build:tui` after changing src/tui.tsx or src/rpc.ts, and
// commit the result; `bun scripts/build-tui.ts --check` (in `bun run check` and the tests) fails when the
// committed file is stale.
//
// Why a build: OpenCode compiles a plugin's .tsx when it loads it, but its Solid transform skips
// files under node_modules, where installed plugins live. And a bare `import "solid-js"` there
// would load a second Solid instead of OpenCode's. So the JSX is compiled here, the way OpenCode
// compiles a local plugin: OpenTUI/Solid imports become `opentui:runtime-module:` ids that resolve
// to OpenCode's own copies. `effect` and `@opencode/plugin/*` stay bare imports, which OpenCode
// also provides, and `zod` is the package's own dependency. The rest (the RPC contract) is bundled in.
import { runtimeModuleIdForSpecifier } from "@opentui/core/runtime-plugin";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";

// Not in the package's exports: load it by path.
const { transformSolidSource } = await import(join(dirname(Bun.resolveSync("@opentui/solid/package.json", import.meta.dir)), "scripts/solid-transform.js")) as {
  transformSolidSource: (code: string, options: { filename: string; moduleName: string; resolvePath: (specifier: string) => string | null }) => Promise<string>;
};

const root = join(import.meta.dir, "..");
const out = join(root, "dist/tui.js");

// The modules OpenCode's TUI provides to plugins (`@opentui/solid/runtime-plugin-support/configure`
// plus OpenCode's `additional` entry).
const RUNTIME = new Set([
  "@opentui/core",
  "@opentui/solid", "@opentui/solid/components", "@opentui/solid/jsx-runtime", "@opentui/solid/jsx-dev-runtime",
  "solid-js", "solid-js/store",
  "@opencode/plugin/tui",
]);

const result = await Bun.build({
  entrypoints: [join(root, "src/tui.tsx")],
  target: "bun",
  format: "esm",
  minify: false,
  external: ["effect", "effect/*", "@opencode/plugin", "@opencode/plugin/*", "zod", "opentui:runtime-module:*"],
  plugins: [{
    name: "uniichat-solid",
    setup(build) {
      build.onLoad({ filter: /\.tsx$/ }, async (args) => ({
        loader: "js",
        contents: await transformSolidSource(await Bun.file(args.path).text(), {
          filename: args.path,
          moduleName: runtimeModuleIdForSpecifier("@opentui/solid"),
          resolvePath: (specifier: string) => RUNTIME.has(specifier) ? runtimeModuleIdForSpecifier(specifier) : null,
        }),
      }));
    },
  }],
});
if (!result.success) {
  for (const log of result.logs) console.error(log);
  process.exit(1);
}
const banner = "// Generated by scripts/build-tui.ts from src/tui.tsx. Do not edit; run `bun run build:tui`.\n";
const code = banner + (await result.outputs[0]!.text());

// Every import left must be one OpenCode provides; anything else would fail only at load time,
// where OpenCode drops a broken TUI plugin silently.
const imports = [...code.matchAll(/^import\s[^;]*?from\s*"([^"]+)"/gm), ...code.matchAll(/^import\s*"([^"]+)"/gm)].map((match) => match[1]!);
const allowed = (specifier: string) => specifier.startsWith("opentui:runtime-module:")
  ? RUNTIME.has(decodeURIComponent(specifier.slice("opentui:runtime-module:".length)))
  : /^(effect|@opencode\/plugin|zod)(\/|$)/.test(specifier);
const bad = imports.filter((specifier) => !allowed(specifier));
// Each name imported from a runtime module must exist in it (the host would fail to link it).
for (const match of code.matchAll(/^import\s*\{([^}]*)\}\s*from\s*"opentui:runtime-module:([^"]+)"/gm)) {
  const specifier = decodeURIComponent(match[2]!);
  const exported = new Set(Object.keys(await import(specifier)));
  for (const name of match[1]!.split(",").map((item) => item.trim().split(/\s+as\s+/)[0]!).filter(Boolean)) {
    if (!exported.has(name)) bad.push(`${specifier} (no export ${name})`);
  }
}
if (bad.length) {
  console.error(`dist/tui.js imports modules OpenCode does not provide: ${[...new Set(bad)].join(", ")}`);
  process.exit(1);
}

if (process.argv.includes("--check")) {
  let committed = "";
  try { committed = readFileSync(out, "utf8"); } catch {}
  if (committed !== code) {
    console.error("dist/tui.js is stale: run `bun run build:tui` and commit it.");
    process.exit(1);
  }
  console.log("dist/tui.js is up to date.");
} else {
  await Bun.write(out, code);
  console.log(`wrote ${out} (${code.length} bytes)`);
}
